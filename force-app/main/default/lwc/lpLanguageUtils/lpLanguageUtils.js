function translateStatus(status, labels) {
    if (!status) {
        return status;
    }
    const key = STATUS_TO_LABEL_KEY[status];
    if (key && labels && labels[key]) {
        return labels[key];
    }
    return status;
}

function toCamel(apiName) {
    const stripped = apiName.replace(/^(LP_|EP_|PP_)/, '');
    const parts = stripped.split('_');
    return parts
        .map((p, i) => {
            const lower = p.toLowerCase();
            return i === 0 ? lower : lower.charAt(0).toUpperCase() + lower.slice(1);
        })
        .join('');
}

function mapApiToCamel(apiMap) {
    const out = {};
    Object.keys(apiMap || {}).forEach((api) => {
        out[toCamel(api)] = apiMap[api];
    });
    return out;
}

